def filter_by_skills(skills_text: str) -> list[dict]:
    if not skills_text:
        return []
    skills_lower = skills_text.lower()
    matches = []
    for idea in SKILL_BASED:
        name_lower = idea["name"].lower()
        if any(s.strip() in name_lower or name_lower in s.strip() for s in skills_lower.split(",")):
            matches.append(idea)
    return matches[:5]


